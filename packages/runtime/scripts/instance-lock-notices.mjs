import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const result = spawnSync("cargo", ["metadata", "--locked", "--offline", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc", "--manifest-path", join(root, "native/instance-lock/Cargo.toml")], { encoding: "utf8", windowsHide: true });
if (result.status !== 0) throw new Error(result.stderr || "cargo metadata failed");
const metadata = JSON.parse(result.stdout);
const notice = metadata.packages.filter((pkg) => pkg.source).sort((a, b) => a.name.localeCompare(b.name)).map((pkg) => {
  const dir = dirname(pkg.manifest_path);
  // OR 双许可选择 MIT；unicode-ident 还必须包含 Unicode 数据许可。
  let files = readdirSync(dir).filter((name) => /^(license|licence)([-_.]mit|[-_.]unicode)?$/i.test(name)).sort();
  if (pkg.name.startsWith("napi")) files = [];
  const body = pkg.name.startsWith("napi") ? readFileSync(join(root, "notices/NAPI-RS-LICENSE"), "utf8") : files.map((name) => readFileSync(join(dir, name), "utf8")).join("\n");
  if (!body) throw new Error(`Missing native dependency notice: ${pkg.name}`);
  return `\n===== ${pkg.name}@${pkg.version} (${pkg.license}) =====\n${body.replaceAll("\r\n", "\n")}`;
}).join("\n");
const path = join(root, "notices/Instance-lock-THIRD-PARTY.txt");
const output = `Windows instance-lock native module dependencies (including build dependencies).\nGenerated by scripts/instance-lock-notices.mjs from Cargo.lock; dual MIT/Apache licenses use MIT.\nNAPI-RS notices are vendored from upstream LICENSE (source revisions in NAPI-RS-LICENSE).\n${notice}`;
if (process.argv.includes("--check")) {
  // Git 的 Windows 检出可将全文转换为 CRLF。仅接受两种一致的换行形式。
  const actual = readFileSync(path, "utf8");
  if (actual !== output && actual !== output.replaceAll("\n", "\r\n")) {
    throw new Error("Native dependency notices drifted; regenerate with node scripts/instance-lock-notices.mjs");
  }
} else writeFileSync(path, output);
