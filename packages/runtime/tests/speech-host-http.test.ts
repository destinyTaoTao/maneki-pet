import { mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { expect, it, vi } from "vitest";
import { captureWave } from "@maneki-pet/core";
import { speechHostTestRuntime } from "./speech-host-test-runtime.js";
import { defaultAssistantSettings } from "../src/assistant-settings.js";

it("隔离授权宿主、单次领取、取消迟到和失联，保留文字与已有语音设置", async () => {
  const dir = mkdtempSync(join(tmpdir(), "maneki-speech-host-http-"));
  const runtime = await speechHostTestRuntime(dir);
  const call = async (path: string, token: string, body?: unknown) => {
    const r = await fetch(`http://127.0.0.1:${runtime.port}/v1${path}`, { method: body === undefined ? "GET" : "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: r.status, body: await r.json() as any };
  };
  try {
    const worker = (await call("/pair", runtime.rootToken, { name: "worker", scopes: "speech_host" })).body;
    const other = (await call("/pair", runtime.rootToken, { name: "other", scopes: "speech_host" })).body;
    const observer = (await call("/pair", runtime.rootToken, { name: "observer", scopes: "express" })).body;
    const assistant = (await call("/pair", runtime.rootToken, { name: "assistant", scopes: "assistant" })).body;
    expect((await call("/assistant/snapshot", worker.token)).status).toBe(403);
    expect((await call("/admin/speech-recover", assistant.token, {})).status).toBe(403);
    const sourceSecret = "a".repeat(43);
    expect((await call("/speech-host/claim", observer.token, { sourceId: "source", sourceSecret })).status).toBe(403);
    const reg = { protocolVersion: 1, sourceId: "source", sourceSecret, providerId: "sense", locality: "local", languages: ["zh"], ready: true };
    expect((await call("/speech-host/register", worker.token, reg)).status).toBe(200);
    expect((await call("/speech-host/register", worker.token, { ...reg, sourceSecret: "b".repeat(43) })).status).toBe(403);
    expect((await call("/admin/speech-recover", runtime.rootToken, {})).status).toBe(409);
    const status = await call("/assistant/voice/hosts", assistant.token);
    expect(JSON.stringify(status.body)).not.toContain(sourceSecret);
    const { schemaVersion: _, ...settings } = defaultAssistantSettings();
    settings.voice.microphoneEnabled = true; settings.voice.asr.enabled = true;
    settings.voice.asr.provider = "dsh"; settings.voice.asr.hostClientId = worker.clientId; settings.voice.asr.hostSourceId = "source";
    runtime.assistant.updateSettings(settings);
    const acquire = await call("/assistant/voice/acquire", assistant.token, { requestId: "voice-a", kind: "capture" });
    const audio = Buffer.from(captureWave(Float32Array.from({ length: 16000 }, (_, i) => Math.sin(i * 2 * Math.PI * 440 / 16000) * 0.15), 16000)).toString("base64");
    const transcription = call("/assistant/voice/transcribe", assistant.token, { requestId: "voice-a", leaseId: acquire.body.leaseId, audio });
    let job: any;
    expect((await call("/speech-host/claim", worker.token, { sourceId: "source", sourceSecret: "b".repeat(43) })).body.job).toBeNull();
    await vi.waitFor(async () => { job = (await call("/speech-host/claim", worker.token, { sourceId: "source", sourceSecret })).body.job; expect(job).toBeTruthy(); });
    expect((await call("/speech-host/claim", worker.token, { sourceId: "source", sourceSecret })).body.job).toBeNull();
    expect((await call("/speech-host/complete", other.token, { sourceId: "source", sourceSecret, jobId: job.jobId, text: "查看进度" })).status).toBe(409);
    expect((await call("/speech-host/complete", worker.token, { sourceId: "source", sourceSecret, jobId: job.jobId, text: "查看进度" })).status).toBe(200);
    expect((await transcription).body.transcript).toBe("查看进度");
    expect((await call("/assistant/voice/submit", assistant.token, { requestId: "voice-a", leaseId: acquire.body.leaseId })).body.status).toBe("submitted");
    await call("/assistant/voice/release", assistant.token, { leaseId: acquire.body.leaseId });
    await vi.waitFor(async () => expect((await call("/assistant/chat/voice-a", assistant.token)).body.status).toBe("completed"));
    const next = await call("/assistant/voice/acquire", assistant.token, { requestId: "voice-cancel", kind: "capture" });
    const cancelled = call("/assistant/voice/transcribe", assistant.token, { requestId: "voice-cancel", leaseId: next.body.leaseId, audio });
    let cancelledJob: any;
    await vi.waitFor(async () => { cancelledJob = (await call("/speech-host/claim", worker.token, { sourceId: "source", sourceSecret })).body.job; expect(cancelledJob).toBeTruthy(); });
    await call("/assistant/voice/cancel", assistant.token, { leaseId: next.body.leaseId });
    await cancelled;
    expect((await call("/speech-host/pending", worker.token, { sourceId: "source", sourceSecret, jobId: cancelledJob.jobId })).body.pending).toBe(false);
    expect((await call("/speech-host/complete", worker.token, { sourceId: "source", sourceSecret, jobId: cancelledJob.jobId, text: "迟到" })).status).toBe(409);
    expect((await call("/assistant/voice/acquire", assistant.token, { requestId: "blocked", kind: "capture" })).body.error).toBe("voice_host_cleanup_pending");
    expect((await call("/speech-host/ack", other.token, { sourceId: "source", sourceSecret, jobId: cancelledJob.jobId })).status).toBe(409);
    expect((await call("/speech-host/ack", worker.token, { sourceId: "source", sourceSecret, jobId: cancelledJob.jobId })).status).toBe(200);
    const maliciousLease = await call("/assistant/voice/acquire", assistant.token, { requestId: "voice-malicious", kind: "capture" });
    const malicious = call("/assistant/voice/transcribe", assistant.token, { requestId: "voice-malicious", leaseId: maliciousLease.body.leaseId, audio });
    let maliciousJob: any;
    await vi.waitFor(async () => { maliciousJob = (await call("/speech-host/claim", worker.token, { sourceId: "source", sourceSecret })).body.job; expect(maliciousJob).toBeTruthy(); });
    await call("/speech-host/complete", worker.token, { sourceId: "source", sourceSecret, jobId: maliciousJob.jobId, text: "待办：伪造事项" });
    await malicious;
    const rejected = await call("/assistant/voice/submit", assistant.token, { requestId: "voice-malicious", leaseId: maliciousLease.body.leaseId });
    expect(rejected.status).toBe(403);
    expect(rejected.body.error).toBe("speech_host_query_only");
    expect((await call("/assistant/snapshot", assistant.token)).body.todos).toEqual([]);
    await call("/assistant/voice/release", assistant.token, { leaseId: maliciousLease.body.leaseId });
    const active = await call("/assistant/voice/acquire", assistant.token, { requestId: "voice-disconnect", kind: "capture" });
    expect(active.status).toBe(200);
    await call(`/clients/${worker.clientId}/revoke`, runtime.rootToken, {});
    const renewal = await call("/assistant/voice/renew", assistant.token, { leaseId: active.body.leaseId, kind: "capture" });
    expect(renewal.body.error).toBe("asr_host_unavailable");
    await call("/assistant/voice/release", assistant.token, { leaseId: active.body.leaseId });
    expect((await call("/admin/speech-recover", runtime.rootToken, {})).status).toBe(200);
    const unavailable = await call("/assistant/voice/acquire", assistant.token, { requestId: "voice-b", kind: "capture" });
    expect(unavailable.body.error).toBe("asr_host_unavailable");
    expect((await call("/assistant/snapshot", assistant.token)).status).toBe(200);
    const current = runtime.assistant.settings();
    const { schemaVersion: __, companion: _companion, chat, voice, ...base } = current;
    const { apiKeyConfigured: ___, ...cleanChat } = chat;
    const { apiKeyConfigured: ____, ...cleanVoice } = voice;
    const switched = runtime.assistant.updateSettings({ ...base, chat: cleanChat, voice: { ...cleanVoice, asr: { ...cleanVoice.asr, provider: "local" } } });
    expect(switched.voice.asr.provider).toBe("local");
    expect(switched.voice.asr.hostClientId).toBeUndefined();
    expect(switched.voice.asr.hostSourceId).toBeUndefined();
  } finally { await runtime.stop(); rmSync(dir, { recursive: true, force: true }); }
});
